import { randomBytes, randomInt } from "node:crypto";
import { access, writeFile } from "node:fs/promises";
import path from "node:path";
import { hardenWindowsPrivatePath } from "@fluxiq-web-extension/test-runner/windows-acl";

if (process.argv.includes("--help")) {
  await Promise.all([import("@fluxiq-web-extension/test-runner/windows-acl"), import("fluxiq")]);
  process.stdout.write("Usage: node scripts/setup-demo-local-env.mjs [command arguments]\n--help  Show help without building, opening a browser or changing workspace data.\n");
  process.exit(0);
}

const repositoryRoot = path.resolve(process.env.FLUXIQ_WEB_EXTENSION_ROOT ?? process.cwd());
const target = path.join(repositoryRoot, ".env.local");
const force = process.argv.includes("--force");
if (!force) {
  let exists = true;
  try {
    await access(target);
  } catch (error) {
    if (error?.code === "ENOENT") exists = false;
    else throw error;
  }
  if (exists) throw new Error(".env.local already exists; rerun with --force only if credential rotation is intended");
}
const username = "web-extension-demo";
const password = "Demo-" + randomBytes(24).toString("base64url") + "!9";
const pin = String(randomInt(100000, 1000000));
const demoWorkspaceRoot = path.join(repositoryRoot, "test-runs", "web-extension-demo");
const demoFluxiqRoot = path.join(demoWorkspaceRoot, "fluxiq-root");

const { FluxIQ } = await import("fluxiq");
const fluxiq = FluxIQ.create({ rootDir: demoFluxiqRoot, loadEnv: false });
await fluxiq.setup();
await fluxiq.programs.identityAccess.upsertUser({
  id: "web-extension-demo-runner",
  username,
  displayName: "Web Extension Demo Runner",
  roleId: "admin",
  enabled: true,
  password,
  pin,
});

const normalizedRoot = repositoryRoot.replaceAll("\\", "/");
const contents = [
  "# Generated by pnpm demo:setup-local. This file is ignored and private.",
  "FLUXIQ_TEST_TARGET=existing",
  "FLUXIQ_TEST_BASE_URL=http://127.0.0.1:3000",
  "FLUXIQ_TEST_GATEWAY_URL=ws://127.0.0.1:4777/client",
  "FLUXIQ_TEST_USERNAME=" + username,
  "FLUXIQ_TEST_PASSWORD=" + password,
  "FLUXIQ_TEST_PIN=" + pin,
  "FLUXIQ_TEST_RUNS_DIR=" + normalizedRoot + "/test-runs",
  "FLUXIQ_DEMO_RUN_DIR=" + normalizedRoot + "/test-runs/web-extension-demo",
  "FLUXIQ_DEMO_BASE_URL=http://127.0.0.1:3300",
  "FLUXIQ_DEMO_GATEWAY_URL=ws://127.0.0.1:4877/client",
  "FLUXIQ_DEMO_PROJECT_NAME=FluxIQ Web Extension Test",
  "FLUXIQ_DEMO_FLOW_ID=flow.web-extension-demo",
  "FLUXIQ_DEMO_FLOW_NAME=Web Extension Demo Flow",
  "",
].join("\n");

await writeFile(target, contents, { encoding: "utf8", flag: force ? "w" : "wx", mode: 0o600 });
if (process.platform === "win32") await hardenWindowsPrivatePath(target, "file");
process.stdout.write(JSON.stringify({ status: "configured", path: target, username, credentialsPrinted: false }) + "\n");
