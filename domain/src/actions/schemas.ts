import type { JsonObject } from "fluxiq/core";
import { WEB_AUTOMATION_EXTRACT_MAX_PAGES } from "./types";
import type { WebAutomationActionType } from "./types";

export type WebAutomationActionDefinition = {
  actionType: WebAutomationActionType;
  label: string;
  description: string;
  parameterSchema: JsonObject;
};

// The identity signals are Core's element-fingerprint signals by name
// (`fingerprinting/element-fingerprint.ts`): `testId`, `accessibleName` and
// `label` are three of its highest-weighted, so a target that carries them
// scores against a candidate instead of falling back to the selector.
const elementFingerprintSchema = {
  type: "object",
  label: "Element fingerprint",
  properties: {
    selector: { type: "string", label: "CSS selector" }, xpath: { type: "string", label: "XPath" },
    id: { type: "string", label: "ID" }, classNames: { type: "array", label: "Class names" },
    visibleText: { type: "string", label: "Visible text" }, tagName: { type: "string", label: "Tag name" },
    role: { type: "string", label: "ARIA role" }, name: { type: "string", label: "Accessible name" },
    href: { type: "string", label: "Link URL" }, attributes: { type: "object", label: "Attributes" },
    testId: { type: "string", label: "Test id" }, accessibleName: { type: "string", label: "Accessible name" },
    label: { type: "string", label: "Label" }
  }
} satisfies JsonObject;

const visualTargetSchema = {
  type: "object",
  label: "Visual target",
  properties: {
    namespace: { type: "string", label: "State namespace" },
    statePath: { type: "string", label: "State path" },
    selector: { type: "string", label: "CSS selector" },
    frameId: { type: "string", label: "Visual frame" },
    layerId: { type: "string", label: "Visual layer" },
    documentLayerId: { type: "string", label: "Document visual layer" },
    bounds: { type: "object", label: "Viewport bounds" },
    documentBounds: { type: "object", label: "Document bounds" },
    anchor: { type: "object", label: "Anchor" },
    confidence: { type: "number", label: "Confidence" },
    metadata: { type: "object", label: "Metadata" }
  }
} satisfies JsonObject;

const elementProperties = { selector: { type: "string", label: "CSS selector" }, element: elementFingerprintSchema, visualTarget: visualTargetSchema };

const selectorSchema = {
  type: "object",
  required: ["selector"],
  properties: {
    ...elementProperties,
    timeoutMs: { type: "integer", label: "Timeout in ms" }
  }
} satisfies JsonObject;

// The structured parameters below are named and shaped exactly as the fields
// of `WebAutomationActionCommand` (`actions/types.ts`). A Flow's parameters
// reach the extension unaltered, so one shape crosses the wire rather than a
// domain shape that some mapper has to reshape into the command's.

/** `WebAutomationWaitRequest`. */
const waitSchema = {
  type: "object",
  label: "Wait condition",
  properties: {
    condition: { type: "string", label: "Condition", enum: ["present", "visible", "enabled", "absent", "url", "stable"] },
    url: { type: "string", label: "URL" },
    stableForMs: { type: "integer", label: "Stable for, in ms" }
  }
} satisfies JsonObject;

/** `WebAutomationKeyModifiers`. */
const keyModifiersSchema = {
  type: "object",
  label: "Modifier keys",
  properties: {
    alt: { type: "boolean", label: "Alt" }, ctrl: { type: "boolean", label: "Control" },
    meta: { type: "boolean", label: "Meta" }, shift: { type: "boolean", label: "Shift" }
  }
} satisfies JsonObject;

/** `WebAutomationOptionSelector`. `by` decides which of the other three names the option. */
const optionSelectorSchema = {
  type: "object",
  label: "Option",
  required: ["by"],
  properties: {
    by: { type: "string", label: "Match by", enum: ["value", "label", "index"] },
    value: { type: "string", label: "Option value" },
    label: { type: "string", label: "Option label" },
    index: { type: "integer", label: "Option index" }
  }
} satisfies JsonObject;

/** `WebAutomationScrollRequest`. `maxScrolls` is required by `untilStable`, so a feed cannot scroll forever. */
const scrollRequestSchema = {
  type: "object",
  label: "Scroll",
  required: ["mode"],
  properties: {
    mode: { type: "string", label: "Mode", enum: ["by", "toElement", "untilStable"] },
    x: { type: "number", label: "X delta" },
    y: { type: "number", label: "Y delta" },
    maxScrolls: { type: "integer", label: "Maximum scrolls" }
  }
} satisfies JsonObject;

const waitForSelectorSchema = {
  type: "object",
  required: ["selector"],
  properties: {
    ...elementProperties,
    timeoutMs: { type: "integer", label: "Timeout in ms" },
    wait: waitSchema
  }
} satisfies JsonObject;

/** `WebAutomationAssertRequest`. `expected` carries the text for `text` and the URL for `url`. */
const assertSchema = {
  type: "object",
  label: "Assertion",
  required: ["kind"],
  properties: {
    kind: { type: "string", label: "Condition", enum: ["exists", "absent", "text", "url", "visible", "enabled"] },
    expected: { type: "string", label: "Expected" },
    timeoutMs: { type: "integer", label: "Timeout in ms" }
  }
} satisfies JsonObject;

/**
 * `WebAutomationExtractListRequest`, the same field forms the scenario
 * contract's extract step uses: a field's selector is read inside each item,
 * `selector@attribute` reads an attribute rather than text, and
 * `column:<header text>` reads the cell under that header, so extraction
 * survives a column reorder.
 */
const extractListSchema = {
  type: "object",
  label: "List extraction",
  required: ["item", "fields"],
  properties: {
    item: { type: "string", label: "Item selector" },
    fields: { type: "object", label: "Field map" },
    paginate: {
      type: "object",
      label: "Pagination",
      required: ["next", "maxPages"],
      properties: {
        next: { type: "string", label: "Next control" },
        maxPages: { type: "integer", label: "Maximum pages", minimum: 1, maximum: WEB_AUTOMATION_EXTRACT_MAX_PAGES }
      }
    },
    maxItems: { type: "integer", label: "Maximum items", minimum: 1 }
  }
} satisfies JsonObject;

/**
 * `WebAutomationUploadRequest`. The content travels inline because the page,
 * not the worker, owns the file input; the domain's byte bounds
 * (`WEB_AUTOMATION_UPLOAD_MAX_FILE_BYTES`, `..._TOTAL_BYTES`) keep an action
 * command bounded on the wire.
 */
const uploadSchema = {
  type: "object",
  label: "Files",
  required: ["files"],
  properties: {
    files: {
      type: "array",
      label: "Files",
      minItems: 1,
      items: {
        type: "object",
        required: ["name", "mimeType", "contentBase64"],
        properties: {
          name: { type: "string", label: "File name" },
          mimeType: { type: "string", label: "MIME type" },
          contentBase64: { type: "string", label: "Base64 content" }
        }
      }
    }
  }
} satisfies JsonObject;

/** `WebAutomationDialogRequest`. `promptText` answers a `prompt`, and only with `accept`. */
const dialogSchema = {
  type: "object",
  label: "Dialog",
  required: ["response"],
  properties: {
    response: { type: "string", label: "Response", enum: ["accept", "dismiss"] },
    promptText: { type: "string", label: "Prompt text" }
  }
} satisfies JsonObject;

/** `WebAutomationTabRequest`. A switch names the tab by id, or by the substring its URL must contain. */
const tabSchema = {
  type: "object",
  label: "Tab",
  required: ["operation"],
  properties: {
    operation: { type: "string", label: "Operation", enum: ["open", "switch", "close"] },
    url: { type: "string", label: "URL" },
    active: { type: "boolean", label: "Activate" },
    tabId: { type: "integer", label: "Tab id" },
    urlPattern: { type: "string", label: "URL contains" }
  }
} satisfies JsonObject;

/** `WebAutomationDownloadRequest`. Without a file name, the next download to complete is awaited. */
const downloadSchema = {
  type: "object",
  label: "Download",
  properties: {
    filename: { type: "string", label: "File name" },
    timeoutMs: { type: "integer", label: "Timeout in ms" }
  }
} satisfies JsonObject;

